drop table if exists public.donors;
drop table if exists public.campaigns;

create table public.donors (
  id bigint generated by default as identity primary key,
  name text not null check(length(trim(name)) between 1 and 100),
  email text not null default '',
  created_at timestamptz not null default now()
);
create table public.campaigns (
  id bigint generated by default as identity primary key,
  title text not null check(length(trim(title)) between 1 and 100),
  description text not null,
  category text not null,
  target_amount numeric(12,2) not null check(target_amount > 0),
  end_date date not null,
  status text not null default 'Active' check(status in ('Active','Completed')),
  created_at timestamptz not null default now()
);
create table public.donations (
  id bigint generated by default as identity primary key,
  donor_id bigint not null references public.donors(id) on delete restrict,
  campaign_id bigint not null references public.campaigns(id) on delete restrict,
  amount numeric(12,2) not null check(amount > 0),
  payment_method text not null check(payment_method in ('UPI','Cash','Bank transfer','Card')),
  donation_date date not null default current_date,
  status text not null default 'Completed' check(status in ('Completed','Pending')),
  notes text not null default '',
  created_at timestamptz not null default now()
);

alter table public.donors enable row level security;
alter table public.campaigns enable row level security;
alter table public.donations enable row level security;
create policy "Classroom demo access" on public.donors for all to anon, authenticated using(true) with check(true);
create policy "Classroom demo access" on public.campaigns for all to anon, authenticated using(true) with check(true);
create policy "Classroom demo access" on public.donations for all to anon, authenticated using(true) with check(true);
grant select,insert,update,delete on public.donors,public.campaigns,public.donations to anon,authenticated;
grant usage,select on sequence public.donors_id_seq,public.campaigns_id_seq,public.donations_id_seq to anon,authenticated;
create index donations_donor_idx on public.donations(donor_id);
create index donations_campaign_idx on public.donations(campaign_id);

